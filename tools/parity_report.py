#!/usr/bin/env python3
"""Run parity_diff on every screen in docs/parity/ and write report/README.md.

A screen is every docs/parity/reference/official-<screen>.png; its pair is
docs/parity/current/z0agent-<screen>.png (+ .xml for both). A screen with no
current capture is listed as FAIL ("no capture").

    python3 tools/parity_report.py [--root docs/parity] [--screens chat,settings]

Exit code: 0 when every screen passes, 1 otherwise.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import parity_diff as pdiff  # noqa: E402


def discover(root: Path):
    ref = root / "reference"
    pre = pdiff.OFFICIAL_PREFIX
    return sorted(p.stem[len(pre):] for p in ref.glob(f"{pre}*.png")) if ref.is_dir() else []


def run(root, out=None, screens=None, th=None, keep_system=False):
    root = Path(root)
    out = Path(out) if out else root / "report"
    rows = []
    for screen in screens or discover(root):
        paths = pdiff.screen_paths(root, screen)
        absent = [p.name for p in paths.values() if not p.is_file()]
        if absent:
            rows.append({"screen": screen, "score": 0, "pass": False, "issues": ["no capture: " + ", ".join(absent)]})
            continue
        r = pdiff.diff_screen(screen, out_dir=out, th=th, keep_system=keep_system, **paths)
        ev = r["evaluation"]
        rows.append(
            {
                "screen": screen,
                "score": ev["score"],
                "pass": ev["pass"],
                "issues": ev["issues"],
                "pixel": r["pixels"]["diff_pct"],
                "line": pdiff.summary_line(r),
            }
        )
    out.mkdir(parents=True, exist_ok=True)
    (out / "README.md").write_text(render(rows))
    return rows


def render(rows):
    n_pass = sum(r["pass"] for r in rows)
    L = [
        "# Parity report",
        "",
        "Generated by `tools/parity_report.py`; do not edit by hand. "
        "See [../README.md](../README.md) for how captures are made and what the thresholds mean.",
        "",
        f"{n_pass}/{len(rows)} screens pass.",
        "",
        "| screen | score | result | pixel diff | top issues |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        link = f"[{r['screen']}]({r['screen']}.md)" if "line" in r else r["screen"]
        issues = "<br>".join(pdiff._md(t) for t in r["issues"][:3]) or "none"
        pixel = f"{r['pixel']:.2f}%" if "pixel" in r else "n/a"
        L.append(f"| {link} | {r['score']} | {'PASS' if r['pass'] else '**FAIL**'} | {pixel} | {issues} |")
    if not rows:
        L.append("| (no screens in reference/) | | | | |")
    L.append("")
    return "\n".join(L)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--root", default="docs/parity")
    p.add_argument("--out", default=None, help="report dir (default <root>/report)")
    p.add_argument("--screens", default=None, help="comma-separated subset")
    pdiff.add_threshold_args(p)
    args = p.parse_args(argv)
    screens = [s for s in args.screens.split(",") if s] if args.screens else None
    rows = run(args.root, args.out, screens, pdiff.thresholds_from(args), args.keep_system)
    for r in rows:
        print(r.get("line") or f"{r['screen']}: FAIL {r['issues'][0]}")
    print(f"{sum(r['pass'] for r in rows)}/{len(rows)} pass; wrote {Path(args.out or Path(args.root) / 'report') / 'README.md'}")
    return 0 if rows and all(r["pass"] for r in rows) else 1


if __name__ == "__main__":
    sys.exit(main())
